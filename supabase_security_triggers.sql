-- ----------------------------------------------------------------------------
-- 5. TRIGGERS DE SEGURIDAD PARA TABLA: notas (Calificaciones Académicas)
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_validar_seguridad_notas()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    -- Validar rango estricto vigesimal (1 a 20)
    IF NEW.nota_numerica IS NULL OR NEW.nota_numerica < 1 OR NEW.nota_numerica > 20 THEN
        RAISE EXCEPTION 'SEGURIDAD (notas): La calificación numérica (%) está fuera del rango permitido (1 a 20).', NEW.nota_numerica;
    END IF;

    -- Sincronizar automáticamente la calificación literal/cuantitativa oficial
    IF NEW.nota_numerica >= 18 THEN
        NEW.nota_cuantitativa := 'AD';
    ELSIF NEW.nota_numerica >= 14 THEN
        NEW.nota_cuantitativa := 'A';
    ELSIF NEW.nota_numerica >= 11 THEN
        NEW.nota_cuantitativa := 'B';
    ELSE
        NEW.nota_cuantitativa := 'C';
    END IF;

    -- Actualizar marca de tiempo automáticamente
    NEW.fecha_actualizado := NOW();

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_notas ON public.notas;
CREATE TRIGGER trg_validar_notas
    BEFORE INSERT OR UPDATE ON public.notas
    FOR EACH ROW
    EXECUTE FUNCTION public.fn_validar_seguridad_notas();

DROP TRIGGER IF EXISTS trg_auditoria_notas ON public.notas;
CREATE TRIGGER trg_auditoria_notas
    AFTER INSERT OR UPDATE OR DELETE ON public.notas
    FOR EACH ROW
    EXECUTE FUNCTION public.fn_registrar_auditoria_seguridad();


-- ----------------------------------------------------------------------------
-- 6. TRIGGERS DE SEGURIDAD PARA TABLA: movimientos (Transacciones Financieras)
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_validar_seguridad_movimientos()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.nombre := BTRIM(COALESCE(NEW.nombre, ''));

    IF NEW.nombre = '' THEN
        RAISE EXCEPTION 'SEGURIDAD (movimientos): Todo movimiento financiero debe tener un concepto o descripción.';
    END IF;

    IF NEW.monto IS NULL OR NEW.monto = 0 THEN
        RAISE EXCEPTION 'SEGURIDAD (movimientos): El monto del movimiento no puede ser nulo ni igual a cero (0).';
    END IF;

    IF NEW.fecha IS NULL THEN
        NEW.fecha := NOW();
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_movimientos ON public.movimientos;
CREATE TRIGGER trg_validar_movimientos
    BEFORE INSERT OR UPDATE ON public.movimientos
    FOR EACH ROW
