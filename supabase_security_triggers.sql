-- ----------------------------------------------------------------------------
-- 8. TRIGGERS DE SEGURIDAD PARA TABLA: facturas (Bóveda de Comprobantes)
-- ----------------------------------------------------------------------------
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.tables 
        WHERE table_schema = 'public' AND table_name = 'facturas'
    ) THEN
        -- Función de validación e inmutabilidad financiera para facturas
        EXECUTE $sql$
        CREATE OR REPLACE FUNCTION public.fn_validar_seguridad_facturas()
        RETURNS TRIGGER
        LANGUAGE plpgsql
        AS $func$
        BEGIN
            NEW.concepto := BTRIM(COALESCE(NEW.concepto, ''));
            NEW.estado := LOWER(BTRIM(COALESCE(NEW.estado, 'emitida')));

            IF NEW.monto IS NULL OR NEW.monto <= 0 THEN
                RAISE EXCEPTION 'SEGURIDAD (facturas): El monto de una factura debe ser estrictamente mayor a 0.';
            END IF;

            IF NEW.concepto = '' THEN
                RAISE EXCEPTION 'SEGURIDAD (facturas): El concepto del comprobante es obligatorio.';
            END IF;

            IF NEW.estado NOT IN ('emitida', 'pagada', 'anulada') THEN
                RAISE EXCEPTION 'SEGURIDAD (facturas): Estado de factura inválido (%). Valores permitidos: emitida, pagada, anulada.', NEW.estado;
            END IF;

            IF TG_OP = 'UPDATE' THEN
                -- Impedir reactivar una factura que ya fue anulada
                IF OLD.estado = 'anulada' AND NEW.estado <> 'anulada' THEN
                    RAISE EXCEPTION 'SEGURIDAD (facturas): Una factura anulada no puede volver a activarse ni cambiar de estado.';
                END IF;

                -- Impedir alterar el monto original de una factura ya emitida
                IF OLD.monto <> NEW.monto THEN
                    RAISE EXCEPTION 'SEGURIDAD (facturas): No se permite alterar el monto de un comprobante ya emitido. Anule la factura y emita una nueva.';
                END IF;
            END IF;

            RETURN NEW;
        END;
        $func$;
        $sql$;

        -- Función para proteger el borrado físico de facturas pagadas
        EXECUTE $sql$
        CREATE OR REPLACE FUNCTION public.fn_proteger_borrado_facturas()
        RETURNS TRIGGER
        LANGUAGE plpgsql
        AS $func$
        BEGIN
            IF OLD.estado = 'pagada' THEN
                RAISE EXCEPTION 'SEGURIDAD (facturas): No se puede eliminar físicamente un comprobante pagado. Primero debe cambiar su estado a "anulada".';
            END IF;
            RETURN OLD;
        END;
        $func$;
        $sql$;

        EXECUTE 'DROP TRIGGER IF EXISTS trg_validar_facturas ON public.facturas';
        EXECUTE 'CREATE TRIGGER trg_validar_facturas BEFORE INSERT OR UPDATE ON public.facturas FOR EACH ROW EXECUTE FUNCTION public.fn_validar_seguridad_facturas()';

        EXECUTE 'DROP TRIGGER IF EXISTS trg_proteger_borrado_facturas ON public.facturas';
        EXECUTE 'CREATE TRIGGER trg_proteger_borrado_facturas BEFORE DELETE ON public.facturas FOR EACH ROW EXECUTE FUNCTION public.fn_proteger_borrado_facturas()';

        EXECUTE 'DROP TRIGGER IF EXISTS trg_auditoria_facturas ON public.facturas';
        EXECUTE 'CREATE TRIGGER trg_auditoria_facturas AFTER INSERT OR UPDATE OR DELETE ON public.facturas FOR EACH ROW EXECUTE FUNCTION public.fn_registrar_auditoria_seguridad()';
    END IF;
END $$;
