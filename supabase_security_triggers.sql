-- ----------------------------------------------------------------------------
-- 1. TABLA DE BITÁCORA DE AUDITORÍA INMUTABLE (auditoria_seguridad)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.auditoria_seguridad (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabla_afectada TEXT NOT NULL,
    operacion TEXT NOT NULL CHECK (operacion IN ('INSERT', 'UPDATE', 'DELETE')),
    registro_id TEXT,
    datos_anteriores JSONB,
    datos_nuevos JSONB,
    rol_ejecutor TEXT DEFAULT current_setting('request.jwt.claim.role', true),
    fecha_evento TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Índices para consultas rápidas de auditoría
CREATE INDEX IF NOT EXISTS idx_auditoria_tabla_fecha 
    ON public.auditoria_seguridad (tabla_afectada, fecha_evento DESC);
CREATE INDEX IF NOT EXISTS idx_auditoria_operacion 
    ON public.auditoria_seguridad (operacion);

-- Habilitar RLS en la tabla de auditoría (solo lectura e inserción por trigger)
ALTER TABLE public.auditoria_seguridad ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir lectura de auditoria" ON public.auditoria_seguridad;
CREATE POLICY "Permitir lectura de auditoria"
    ON public.auditoria_seguridad
    FOR SELECT
    USING (true);

-- Función que impide modificar o borrar registros de auditoría (Inmutabilidad Forense)
CREATE OR REPLACE FUNCTION public.fn_proteger_bitacora_auditoria()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    RAISE EXCEPTION 'SEGURIDAD: Los registros de la bitácora de auditoría (auditoria_seguridad) son inmutables y no pueden ser modificados ni eliminados.';
END;
$$;

DROP TRIGGER IF EXISTS trg_proteger_auditoria ON public.auditoria_seguridad;
CREATE TRIGGER trg_proteger_auditoria
    BEFORE UPDATE OR DELETE ON public.auditoria_seguridad
    FOR EACH ROW
    EXECUTE FUNCTION public.fn_proteger_bitacora_auditoria();


-- ----------------------------------------------------------------------------
-- 2. FUNCIÓN GENÉRICA DE AUDITORÍA AUTOMÁTICA (CON SANITIZACIÓN DE CONTRASEÑAS)
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_registrar_auditoria_seguridad()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_old_json JSONB := NULL;
    v_new_json JSONB := NULL;
    v_record_id TEXT := NULL;
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        v_old_json := to_jsonb(OLD);
        -- Ocultar contraseña en los logs de auditoría por privacidad
        IF v_old_json ? 'password' THEN
            v_old_json := jsonb_set(v_old_json, '{password}', '"***PROTEGIDO***"');
        END IF;
        v_record_id := COALESCE(v_old_json->>'id', 'desconocido');
    END IF;

    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        v_new_json := to_jsonb(NEW);
        IF v_new_json ? 'password' THEN
            v_new_json := jsonb_set(v_new_json, '{password}', '"***PROTEGIDO***"');
        END IF;
        v_record_id := COALESCE(v_new_json->>'id', v_record_id, 'desconocido');
    END IF;

    INSERT INTO public.auditoria_seguridad (
        tabla_afectada,
        operacion,
        registro_id,
        datos_anteriores,
        datos_nuevos,
        rol_ejecutor,
        fecha_evento
    ) VALUES (
        TG_TABLE_NAME,
        TG_OP,
        v_record_id,
        v_old_json,
        v_new_json,
        COALESCE(current_setting('request.jwt.claim.role', true), current_user),
        NOW()
    );

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;


-- ----------------------------------------------------------------------------
-- 3. TRIGGERS DE SEGURIDAD PARA TABLA: usuarios (Docentes y Administradores)
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_validar_seguridad_usuarios()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_admin_count INTEGER;
BEGIN
    -- Normalizar espacios en blanco
    NEW.nombre := BTRIM(COALESCE(NEW.nombre, ''));
    NEW.apellido := BTRIM(COALESCE(NEW.apellido, ''));
    NEW.dni := BTRIM(COALESCE(NEW.dni, ''));
    NEW.rol := LOWER(BTRIM(COALESCE(NEW.rol, 'profesor')));

    -- Validar campos obligatorios
    IF NEW.nombre = '' OR NEW.apellido = '' THEN
        RAISE EXCEPTION 'SEGURIDAD (usuarios): El nombre y apellido del usuario son obligatorios.';
    END IF;

    IF LENGTH(NEW.dni) < 8 THEN
        RAISE EXCEPTION 'SEGURIDAD (usuarios): El DNI debe tener al menos 8 caracteres válidos.';
    END IF;

    -- Validar roles permitidos
    IF NEW.rol NOT IN ('admin', 'teacher', 'profesor') THEN
        RAISE EXCEPTION 'SEGURIDAD (usuarios): Rol no autorizado (%). Solo se permite admin, teacher o profesor.', NEW.rol;
    END IF;

    -- Validar que la contraseña no quede vacía
    IF NEW.password IS NULL OR LENGTH(BTRIM(NEW.password)) < 4 THEN
        RAISE EXCEPTION 'SEGURIDAD (usuarios): La contraseña no puede estar vacía ni tener menos de 4 caracteres.';
    END IF;

    -- Impedir degradar de rol al último administrador del sistema
    IF TG_OP = 'UPDATE' AND OLD.rol = 'admin' AND NEW.rol <> 'admin' THEN
        SELECT COUNT(*) INTO v_admin_count
        FROM public.usuarios
        WHERE rol = 'admin' AND id <> OLD.id;

        IF v_admin_count = 0 THEN
            RAISE EXCEPTION 'SEGURIDAD (usuarios): No se puede quitar el rol de administrador al único administrador activo del sistema.';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_proteger_ultimo_admin()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_admin_count INTEGER;
BEGIN
    IF OLD.rol = 'admin' THEN
        SELECT COUNT(*) INTO v_admin_count
        FROM public.usuarios
        WHERE rol = 'admin' AND id <> OLD.id;

        IF v_admin_count = 0 THEN
            RAISE EXCEPTION 'SEGURIDAD (usuarios): Operación bloqueada. No se puede eliminar al último administrador del sistema.';
        END IF;
    END IF;

    RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_usuarios ON public.usuarios;
CREATE TRIGGER trg_validar_usuarios
    BEFORE INSERT OR UPDATE ON public.usuarios
    FOR EACH ROW
    EXECUTE FUNCTION public.fn_validar_seguridad_usuarios();

DROP TRIGGER IF EXISTS trg_proteger_ultimo_admin ON public.usuarios;
CREATE TRIGGER trg_proteger_ultimo_admin
    BEFORE DELETE ON public.usuarios
    FOR EACH ROW
    EXECUTE FUNCTION public.fn_proteger_ultimo_admin();

DROP TRIGGER IF EXISTS trg_auditoria_usuarios ON public.usuarios;
CREATE TRIGGER trg_auditoria_usuarios
    AFTER INSERT OR UPDATE OR DELETE ON public.usuarios
    FOR EACH ROW
    EXECUTE FUNCTION public.fn_registrar_auditoria_seguridad();


-- ----------------------------------------------------------------------------
-- 4. TRIGGERS DE SEGURIDAD PARA TABLA: estudiantes (Alumnos)
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_validar_seguridad_estudiantes()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    -- Normalizar datos
    NEW.nombre := BTRIM(COALESCE(NEW.nombre, ''));
    NEW.apellido := BTRIM(COALESCE(NEW.apellido, ''));
    NEW.dni := BTRIM(COALESCE(NEW.dni, ''));
    NEW.estado := LOWER(BTRIM(COALESCE(NEW.estado, 'activo')));

    IF NEW.nombre = '' OR NEW.apellido = '' THEN
        RAISE EXCEPTION 'SEGURIDAD (estudiantes): El nombre y apellido del estudiante son obligatorios.';
    END IF;

    IF NEW.dni = '' THEN
        RAISE EXCEPTION 'SEGURIDAD (estudiantes): El DNI del estudiante es obligatorio.';
    END IF;

    IF NEW.estado NOT IN ('activo', 'inactivo', 'retirado', 'active', 'inactive') THEN
        RAISE EXCEPTION 'SEGURIDAD (estudiantes): Estado de estudiante no válido (%).', NEW.estado;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_estudiantes ON public.estudiantes;
CREATE TRIGGER trg_validar_estudiantes
    BEFORE INSERT OR UPDATE ON public.estudiantes
    FOR EACH ROW
